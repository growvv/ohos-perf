/** HapRay emits trace insertion order; the public output sorts by name. */
function byThreadName(
  a: { thread_name: string },
  b: { thread_name: string },
): number {
  if (a.thread_name < b.thread_name) return -1;
  if (a.thread_name > b.thread_name) return 1;
  return 0;
}

